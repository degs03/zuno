export const LANGUAGES: Array<{ code: string; name: string }> = [
  { code: "es", name: "Español" },
  { code: "en", name: "English" },
  { code: "pt", name: "Português" },
  { code: "fr", name: "Français" },
  { code: "de", name: "Deutsch" },
  { code: "it", name: "Italiano" },
];
const TABLES: Record<string, Table> = { en, es, pt, fr, de, it };
const LANG_KEY = "zuno.tv.lang";

function systemLanguage(): string {
  const raw = (navigator.language || "es").toLowerCase().slice(0, 2);
  return TABLES[raw] ? raw : "en";
}

let choice: string = (() => {
  try {
    return localStorage.getItem(LANG_KEY) || "auto";
  } catch {
    return "auto";
  }
})();

export function languageChoice(): string {
  return choice;
}

export function setLanguageChoice(next: string): void {
  choice = next;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    // Not persisted; applies for this session.
  }
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const lang = choice === "auto" ? systemLanguage() : choice;
  let text = (TABLES[lang] && TABLES[lang][key]) || en[key];
  if (vars) for (const name in vars) text = text.replace("{" + name + "}", String(vars[name]));
  return text;
}

/** Shelf titles the desktop sends in English for the TV to translate. */
export function shelfTitle(title: string): string {
  return title === "Recently played" ? t("lib.recent") : title;
}
